export function getDefaultTemplate() {
  return PROMPT_TEMPLATES[0];
}

export function getTemplateById(id) {
  return PROMPT_TEMPLATES.find(t => t.id === id) || PROMPT_TEMPLATES[0];
}

export function nextTemplate(currentId) {
  const idx = PROMPT_TEMPLATES.findIndex(t => t.id === currentId);
  return PROMPT_TEMPLATES[(idx + 1) % PROMPT_TEMPLATES.length];
}
